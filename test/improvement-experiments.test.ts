import test from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { ExperimentEvaluator, type ExperimentSpec } from "../src/improvement-experiments.js";
const exec = promisify(execFile);
test("trusted evaluator compares detached revisions and rejects regressions and ties", async (t) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "experiment-test-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = async (...args: string[]) => (await exec("git", ["-C", root, ...args])).stdout.trim();
  await git("init"); await git("config", "user.name", "Test"); await git("config", "user.email", "test@example.invalid");
  const commit = async (score: number, checksPassed = true) => {
    await writeFile(path.join(root, "measurement.json"), JSON.stringify({ score, checksPassed }));
    await git("add", "measurement.json"); await git("commit", "-m", `score ${score}`); return git("rev-parse", "HEAD");
  };
  const baseline = await commit(10), candidate = await commit(8), regression = await commit(6, false), tie = await commit(10);
  const source = "import {readFile} from 'node:fs/promises'; console.log(await readFile(process.argv[2]+'/measurement.json','utf8'));";
  const runner = path.join(root, "runner.mjs"); await writeFile(runner, source);
  const evidence = path.join(root, "evidence");
  const hash = createHash("sha256").update(source).digest("hex");
  const evaluator = new ExperimentEvaluator(root, evidence, runner, hash);
  const spec: ExperimentSpec = { baseline, candidate, hypothesis: "Reduce cost without regressions", metric: "cost", direction: "lower", minimumDelta: 1 };
  const evaluating = evaluator.evaluate(spec);
  await assert.rejects(evaluator.evaluate(spec), /busy/);
  const result = await evaluating;
  assert.equal(result.verdict, "improved");
  assert.equal(JSON.parse(await readFile(path.join(evidence, result.id + ".json"), "utf8")).runnerHash, hash);
  assert.equal((await evaluator.evaluate({ ...spec, candidate: regression })).verdict, "rejected");
  assert.equal((await evaluator.evaluate({ ...spec, candidate: tie })).verdict, "rejected");
  assert.equal((await evaluator.evaluate({ ...spec, baseline: regression })).verdict, "inconclusive");
  assert.equal((await git("worktree", "list", "--porcelain")).split("worktree ").length, 2);
  await writeFile(runner, "changed");
  await assert.rejects(evaluator.evaluate(spec), /integrity mismatch/);
  await writeFile(runner, source);
  assert.equal((await evaluator.evaluate(spec)).verdict, "improved", "failed validation releases reservation");
  assert.equal(await git("rev-parse", "HEAD"), tie, "primary checkout untouched");
});
