import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { ExecutionStore } from "../src/execution.js";
import { DispatcherRuntime } from "../src/dispatcher-runtime.js";
import { Harness } from "../src/harness.js";
import { FakeRuntime, MemoryChannel, ROOM } from "./fakes.js";
import { NativeActivityDelivery } from "../src/builtin-plugins/native-activity.js";
import type { ActivityEvent } from "../src/activity.js";

test("parallel original task contexts survive queued/worker/classifier/status/restart and late delivery", async t => {
  const home = await mkdtemp(path.join(tmpdir(), "visible-context-"));
  t.after(() => rm(home, {recursive: true, force: true}));
  const file = path.join(home, "executions.json");
  let store = new ExecutionStore(file); await store.load();
  const a = await store.submit("parent", "a", "SECRET APPOINTMENT", "direct", 1, {key: "a", scope: "s", checkpoint: {at: 1}, anchor: {id: "a", task: "SECRET APPOINTMENT", receivedAt: 1, outputTags: ["appointment"]}});
  const b = await store.submit("parent", "b", "SECRET SECURITY", "direct", 1, {key: "b", scope: "s", checkpoint: {at: 1}, anchor: {id: "b", task: "SECRET SECURITY", receivedAt: 1, outputTags: ["security"]}});
  const ca = await store.claim(a.id), cb = await store.claim(b.id);
  store = new ExecutionStore(file); await store.load();
  const h = new Harness({runtime: new FakeRuntime()}); h.state("parent").replyTo = ROOM;
  // Deliberately give the current conversation an unrelated focus.
  h.state("parent").outputTags = ["current-topic"];
  const rows: string[] = [];
  const native = new NativeActivityDelivery(path.join(home, "activity.json"), async (_to, _id, text) => {rows.push(text);}, 60000);
  t.after(() => native.stop());
  h.addChannel(Object.assign(new MemoryChannel(), {taskActivity: (_to: unknown, event: ActivityEvent) => native.event(ROOM, event)}));
  const bridge = new DispatcherRuntime(h, store);
  for (const task of [a, b]) {
    const text = bridge.eventText({id: "queued", parent: "parent", executionId: task.id, type: "status", text: "ready", delivered: false});
    assert.ok(text.startsWith(`task ${task.id} · #${task === a ? "appointment" : "security"}`));
  }
  for (const phase of ["running", "blocked", "completed"] as const) {
    for (const [task, claim] of [[b, cb], [a, ca]] as const) {
      const role = task === a ? "worker" : "dispatcher-classifier";
      if (role === "worker") {
        bridge.channel.taskActivity!( {channel: "dispatch", target: `${task.id}:${claim.token}`}, {type: "activity", kind: "progress", snapshot: {id: `worker-${task.id}`, role, context: "worker", phase, outputTags: ["spoof"], activity: "safe", tools: [], elapsedMs: 0, inactiveMs: 0}}, {sessionKey: `dispatch:${task.id}:${claim.token}`, source: "host", text: "SECRET"});
      } else {
        // Classifier snapshots are generated by the host bridge from this same anchor.
        native.event(ROOM, {type: "activity", kind: "progress", snapshot: {id: `classifier-${task.id}`, parent: task.id, role, context: "worker", phase, outputTags: store.list("parent").find(r => r.id === task.id)!.dependency!.anchor!.outputTags, activity: "safe", tools: [], elapsedMs: 0, inactiveMs: 0}});
      }
      await native.flush();
      assert.ok(rows.at(-1)!.startsWith(`task ${task.id} · #${task === a ? "appointment" : "security"}`));
      assert.doesNotMatch(rows.at(-1)!, /SECRET|spoof|current-topic/);
    }
  }
  const foreign = bridge.eventText({id: "foreign", parent: "other-parent", executionId: a.id, type: "status", text: "ready", delivered: false});
  assert.ok(foreign.includes("context unknown")); assert.doesNotMatch(foreign, /appointment/);
});
