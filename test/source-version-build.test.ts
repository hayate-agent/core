import assert from "node:assert/strict";
import { test } from "node:test";
import { execFileSync } from "node:child_process";
import { mkdtemp, mkdir, writeFile, readFile, copyFile, rm } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { randomUUID } from "node:crypto";
import { pathToFileURL } from "node:url";

test("older native owner bootstrap reports release-based versions from exact source, without relabeling official builds", async t => {
  const base = await mkdtemp(path.join(os.tmpdir(), "source-version-build-")); t.after(() => rm(base, { recursive: true, force: true }));
  const origin = path.join(base, "origin"), parent = path.join(base, "software-updates/releases", randomUUID()), core = path.join(parent, "core");
  await mkdir(origin); await mkdir(path.join(core, "scripts"), { recursive: true }); await mkdir(path.join(core, "dist"));
  await mkdir(path.join(parent, "plugins")); await mkdir(path.join(parent, "webui"));
  await writeFile(path.join(parent, "webui/package.json"), "{}");
  const git = (cwd: string, ...args: string[]) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  git(origin, "init", "--quiet"); git(origin, "config", "user.name", "Fixture"); git(origin, "config", "user.email", "fixture@example.org");
  await writeFile(path.join(origin, "file"), "released"); git(origin, "add", "."); git(origin, "commit", "--quiet", "-m", "released"); git(origin, "tag", "-a", "v0.1.252", "-m", "release");
  await writeFile(path.join(origin, "file"), "development"); git(origin, "commit", "-am", "development", "--quiet"); const revision = git(origin, "rev-parse", "HEAD");
  git(core, "init", "--quiet"); git(core, "remote", "add", "origin", origin); git(core, "fetch", "--depth=1", "origin", revision); git(core, "checkout", "--detach", "FETCH_HEAD");
  await writeFile(path.join(core, "package.json"), '{"type":"module","version":"0.1.0"}');
  const web = path.join(parent, "webui");
  await writeFile(path.join(web, "package.json"), '{"version":"0.1.0"}');
  git(web, "init", "--quiet"); git(web, "config", "user.name", "Fixture"); git(web, "config", "user.email", "fixture@example.org");
  git(web, "add", "."); git(web, "commit", "--quiet", "-m", "Web release"); git(web, "tag", "v0.2.1"); git(web, "remote", "add", "origin", web);
  await copyFile("scripts/build-source-version.mjs", path.join(core, "scripts/build-source-version.mjs"));
  await copyFile("dist/source-version.js", path.join(core, "dist/source-version.js")); await copyFile("dist/build-info.js", path.join(core, "dist/build-info.js"));
  execFileSync(process.execPath, [path.join(core, "scripts/build-source-version.mjs")], { timeout: 20000 });
  const metadata = JSON.parse(await readFile(path.join(core, "dist/source-build-info.json"), "utf8"));
  assert.equal(metadata.version, `0.1.252+dev.${revision.slice(0, 12)}`); assert.equal(metadata.revision, revision);
  await writeFile(path.join(core, "build-info.json"), JSON.stringify({ version: "0.1.0", revision }));
  const module = await import(pathToFileURL(path.join(core, "dist/build-info.js")).href + "?native");
  assert.deepEqual(module.BUILD_INFO, { version: metadata.version, revision });
  assert.equal(metadata.webPackage.version, "0.2.1");
  assert.equal(metadata.webPackage.revision, git(web, "rev-parse", "HEAD"));
  await writeFile(path.join(core, "build-info.json"), JSON.stringify({ version: "0.1.253", revision }));
  const official = await import(pathToFileURL(path.join(core, "dist/build-info.js")).href + "?official");
  assert.equal(official.BUILD_INFO.version, "0.1.253");
});
